String marketLocale(BuildContext context) {
  final l = AppStrings.of(context).locale;
  return l.languageCode == 'en'
      ? 'en'
      : l.countryCode == 'TW' || l.scriptCode == 'Hant'
      ? 'hant'
      : 'cn';
}

/// [marketText] with a {n} placeholder filled in.
String marketTextN(BuildContext context, String key, Object n) =>
    marketText(context, key).replaceAll('{n}', '$n');

String marketText(BuildContext context, String key) {
  final values = _copy[key];
  if (values == null) return key;
  return values[marketLocale(context) == 'en'
      ? 2
      : marketLocale(context) == 'hant'
      ? 1
      : 0];
}

