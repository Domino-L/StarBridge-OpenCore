  BuildContext context,
  String key, [
  Map<String, String> args = const {},
]) => tradeTextFor(marketLocale(context), key, args);
String tradeTextFor(
  String locale,
  String key, [
  Map<String, String> args = const {},
]) {
  final values = tradeCopy[key];
  var text = values == null
      ? key
      : values[locale == 'en'
            ? 2
            : locale == 'hant'
            ? 1
            : 0];
  for (final entry in args.entries) {
    text = text.replaceAll('{${entry.key}}', entry.value);
  }
  return text;
}

