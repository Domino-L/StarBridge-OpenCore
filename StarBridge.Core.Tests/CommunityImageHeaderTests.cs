using StarBridge.Communities;

internal static class CommunityImageHeaderTests
{
    internal static void Run()
    {
        var assertions = 0;
        void Check(bool value, string name)
        {
            assertions++;
            if (!value) throw new InvalidOperationException(name);
        }
        void Accept(byte[] bytes, string mime = "png")
        {
            var source = CommunityImageFixtures.Data(bytes, mime);
            Check(CommunityImageUpload.Normalize(source) == source, $"valid {mime} header rejected");
        }

        Accept(CommunityImageFixtures.Png());
        foreach (var color in new byte[] { 0, 2, 3, 4, 6 })
            foreach (var depth in new byte[] { 1, 2, 4, 8, 16 })
            {
                var legal = color == 0 || (color == 3 ? depth != 16 : depth is 8 or 16);
                foreach (var interlace in new byte[] { 0, 1 })
                    Check((CommunityImageUpload.Normalize(CommunityImageFixtures.Data(
                        CommunityImageFixtures.PngHeader(depth, color, interlace: interlace))) is not null) == legal,
                        $"PNG depth {depth}, color {color}, interlace {interlace}");
            }
        // Independent known PNG CRC vector, not generated by the fixture CRC implementation.
        Accept(Convert.FromHexString("89504E470D0A1A0A0000000D49484452000000010000000108060000001F15C489"));
        Accept(CommunityImageFixtures.Jpeg(), "jpeg");
        Accept(CommunityImageFixtures.Png(4096, 4096));
        foreach (var marker in new byte[] { 0xC0, 0xC1, 0xC2 })
        {
            Accept(CommunityImageFixtures.JpegHeader(4096, 4096, marker), "jpeg");
            // APP payload contains a false SOF; parser must skip by segment length.
            var prefix = new byte[] { 0xFF, 0xD8, 0xFF, 0xFF, 0xE1, 0, 6, 0xFF, 0xC0, 0, 0, 0xFF, 1 };
            Accept(prefix.Concat(CommunityImageFixtures.JpegHeader(marker: marker)[2..]).ToArray(), "jpeg");
        }
        Check(CommunityImageUpload.Normalize(CommunityImageFixtures.Boundary()) is not null, "2 MiB PNG boundary");
        var jpegBoundary = new byte[CommunityImageUpload.MaximumBytes];
        CommunityImageFixtures.Jpeg().CopyTo(jpegBoundary, 0);
        Accept(jpegBoundary, "jpeg");
        Check(CommunityImageUpload.Normalize(CommunityImageFixtures.Data(new byte[jpegBoundary.Length + 1], "jpeg")) is null,
            "JPEG byte limit");
        foreach (var invalid in CommunityImageFixtures.Invalid())
            Check(CommunityImageUpload.Normalize(invalid) is null, "original and extended invalid image fixtures");
        foreach (var (name, image) in CommunityImageFixtures.InvalidHeaders())
            Check(CommunityImageUpload.Normalize(image) is null, name);
        Check(CommunityImageUpload.Normalize(null) is null, "null rejected");
        Console.WriteLine($"PASS community image header assertions: {assertions}");
    }
}
